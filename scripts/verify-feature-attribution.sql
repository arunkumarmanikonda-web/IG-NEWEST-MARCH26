begin;
do $$ declare
  a record; campaign uuid; p jsonb; root text:=repeat('conversion-test-',5); e uuid; r jsonb;
  buyer uuid; own_jwt text; buyer_jwt text;
begin
  select * into a from public.ig_public_content where kind='opportunity' order by slug limit 1;
  update public.ig_public_content set public_data=public_data-'reference'-'availability' where id=a.id;
  insert into ig_private.listing_features(content_id,slot,starts_at,ends_at) values(a.id,1,now()-interval '7 days',now()+interval '1 minute') returning id into campaign;
  update ig_private.ingest_config set secret_hash=encode(extensions.digest(root,'sha256'),'hex');
  p=jsonb_build_object('request_id',gen_random_uuid(),'feature_id',campaign,'listing_slug',a.slug,'name','Fixture Contact','email','nobody@example.invalid','message','Synthetic integration test only.','practice',left(a.title,120),'privacy',true,'rate_key',repeat('1',64));
  e=(public.ig_submit_enquiry(root,p)->>'id')::uuid;
  assert (select feature_id=campaign from public.ig_enquiries where id=e), 'attribution missing';
  assert (public.ig_submit_enquiry(root,p)->>'id')::uuid=e, 'duplicate on retry';
  assert ig_private.conversion_feature(campaign::text,a.slug,'HORECA') is null, 'other interest wrongly attributed';
  assert ig_private.conversion_feature(campaign::text,'unknown') is null, 'other listing wrongly attributed';
  update ig_private.listing_features set ends_at=now()-interval '2 minutes' where id=campaign;
  assert ig_private.conversion_feature(campaign::text,a.slug)=campaign, 'in-funnel sign-in failed';
  update ig_private.listing_features set ends_at=now()-interval '30 hours' where id=campaign;
  assert ig_private.conversion_feature(campaign::text,a.slug) is null, 'obsolete referral wrongly attributed';
  assert (public.ig_submit_enquiry(root,p)->>'id')::uuid=e, 'retry after expiry failed';
  update ig_private.listing_features set ends_at=now()+interval '1 day',deadline=now()-interval '3 days' where id=campaign;
  assert ig_private.conversion_feature(campaign::text,a.slug) is null, 'verified deadline ignored';
  update ig_private.listing_features set stopped_at=now(), deadline=null where id=campaign;
  assert ig_private.conversion_feature(campaign::text,a.slug) is null, 'manually stopped campaign credited';
  update ig_private.listing_features set stopped_at=null where id=campaign;
  assert ig_private.conversion_feature('bad',a.slug) is null, 'malformed campaign not ignored';
  update ig_private.listing_features set ends_at=now()+interval '1 day' where id=campaign;
  select jsonb_build_object('sub',u.id,'session_id',s.id,'role','authenticated','aal','aal2')::text into own_jwt from auth.users u join auth.sessions s on s.user_id=u.id where u.email='owner@example.invalid';
  select u.id,jsonb_build_object('sub',u.id,'session_id',s.id,'role','authenticated','aal','aal1')::text into buyer,buyer_jwt from auth.users u join auth.sessions s on s.user_id=u.id where u.email='buyer@example.invalid';
  update public.ig_profiles set policy_version=ig_private.current_policy() where id=buyer;
  insert into public.ig_consents(user_id,purpose,granted,version,policy_hash) select buyer,'registration',true,version,sha256 from public.ig_policy_releases where current;
  perform set_config('request.jwt.claims',own_jwt,true);
  perform public.ig_enquiry_update(jsonb_build_object('id',e,'status','in_progress','qualified',true));
  assert (select qualified_at is not null from public.ig_enquiries where id=e), 'qualification missing';
  perform public.ig_enquiry_update(jsonb_build_object('id',e,'status','closed'));
  assert (select qualified_at is not null from public.ig_enquiries where id=e), 'closing lost qualification';
  perform public.ig_enquiry_update(jsonb_build_object('id',e,'status','closed','qualified',false));
  assert (select qualified_at is null from public.ig_enquiries where id=e), 'qualification correction ignored';
  insert into public.ig_data_rooms(content_id,title) values(a.id,'Synthetic room') on conflict(content_id) do update set active=true;
  perform set_config('request.jwt.claims',buyer_jwt,true);
  r=public.ig_project_signature(jsonb_build_object('action','request','slug',a.slug,'purpose','Review a synthetic opportunity', 'feature_id',campaign));
  assert (r->>'feature_id')::uuid=campaign,'room request lost attribution';
  assert (public.ig_project_signature(jsonb_build_object('action','request','slug',a.slug,'purpose','Review again'))->>'id') = r->>'id','duplicate room request';
end $$;
rollback;
