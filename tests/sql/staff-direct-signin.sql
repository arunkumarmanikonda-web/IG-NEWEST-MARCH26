-- Verifies the authenticator/email choice with all changes rolled back.
begin;
do $$
declare uid uuid=gen_random_uuid();sid uuid=gen_random_uuid();mail text;claims jsonb;
 result jsonb;denied boolean=false;before_count bigint;
begin
 mail='signin-rollback-'||uid::text||'@example.org';
 insert into auth.users(id,email,email_confirmed_at,is_anonymous) values(uid,mail,now(),false);
 insert into auth.sessions(id,user_id,created_at,updated_at) values(sid,uid,now(),now());
 update public.ig_profiles set roles=array['owner'],policy_version='accepted-earlier',must_change_password=false where id=uid;
 insert into public.ig_consents(user_id,purpose,granted,version,policy_hash) values(uid,'registration',true,'accepted-earlier','original-hash');
 claims=jsonb_build_object('sub',uid,'session_id',sid,'email',mail,'aal','aal1','role','authenticated');
 perform set_config('request.jwt.claims',claims::text,true);
 assert not ig_private.allowed('admin.read'),'Missing AMR bypassed verification';
 perform set_config('request.jwt.claims',(claims||'{"amr":[{"method":"password"}]}')::text,true);
 assert not ig_private.allowed('admin.read'),'Password-only session bypassed verification';
 perform set_config('request.jwt.claims',(claims||'{"amr":[{"method":"recovery"}]}')::text,true);
 assert not ig_private.allowed('admin.read'),'Recovery token bypassed verification';
 perform set_config('request.jwt.claims',(claims||'{"amr":[{"method":"email/signup"}]}')::text,true);
 assert not ig_private.allowed('admin.read'),'Signup token bypassed verification';
 perform set_config('request.jwt.claims',(claims||'{"user_metadata":{"amr":[{"method":"otp"}],"roles":["owner"]}}')::text,true);
 assert not ig_private.allowed('admin.read'),'User metadata bypassed verification';
 perform set_config('request.jwt.claims',(claims||'{"amr":[{"method":"otp"}]}')::text,true);
 assert ig_private.allowed('admin.read'),'Email-code owner blocked';
 assert ig_private.allowed('settings.manage'),'Verified owner rights lost';
 perform public.ig_admin_overview();
 assert (public.ig_signin_status()->>'accepted')::bool,'Previous consent not recognised';
 select count(*) into before_count from public.ig_consents where user_id=uid;
 perform public.ig_account_update('{"action":"accept_policies"}');
 assert (select count(*)=before_count from public.ig_consents where user_id=uid),'Duplicate consent created';
 assert (select policy_version='accepted-earlier' from public.ig_profiles where id=uid),'Original policy version overwritten';
 assert (select policy_hash='original-hash' from public.ig_consents where user_id=uid),'Original consent hash overwritten';
 perform set_config('request.jwt.claims',(claims||'{"aal":"aal2","amr":[{"method":"totp"}]}')::text,true);
 assert ig_private.allowed('admin.read'),'Authenticator-verified owner blocked';
 perform set_config('request.jwt.claims',(claims||'{"amr":[{"method":"otp"}]}')::text,true);
 update public.ig_profiles set roles=array['administrator'] where id=uid;
 assert ig_private.allowed('admin.read'),'Verified administrator blocked';
 assert not ig_private.allowed('settings.manage'),'Administrator gained owner-only rights';
 update public.ig_profiles set roles=array['sales'] where id=uid;
 assert ig_private.allowed('enquiries.manage'),'Sales permissions lost';
 assert not ig_private.allowed('users.manage'),'Sales gained user administration';
 update public.ig_profiles set roles=array['client'] where id=uid;
 assert not ig_private.allowed('admin.read'),'Client gained staff access';
 result=public.ig_accept_invitation();
 assert result->>'accepted'='false','Client promoted without invitation';
 insert into ig_private.staff_invites(email,roles,revoked,require_password_change) values(mail,array['administrator'],true,true);
 result=public.ig_accept_invitation();
 assert result->>'accepted'='false','Revoked invitation accepted';
 update ig_private.staff_invites set revoked=false where email=mail;
 perform set_config('request.jwt.claims',(claims||'{"amr":[{"method":"password"}]}')::text,true);
 begin perform public.ig_accept_invitation(); exception when insufficient_privilege then denied=true;end;
 assert denied,'Password-only invitation activated';
 perform set_config('request.jwt.claims',(claims||'{"amr":[{"method":"otp"}]}')::text,true);
 update public.ig_profiles set must_change_password=true where id=uid;
 denied=false;
 begin perform public.ig_accept_invitation(); exception when insufficient_privilege then denied=true;end;
 assert denied,'New staff password requirement bypassed';
 update public.ig_profiles set must_change_password=false where id=uid;
 result=public.ig_accept_invitation();
 assert result->>'accepted'='true','Verified approved invitation did not activate';
 assert (select require_password_change from ig_private.staff_invites where email=mail),'Invitation password requirement altered';
 update public.ig_profiles set status='suspended' where id=uid;
 assert not ig_private.allowed('admin.read'),'Suspended staff gained access';
 update public.ig_profiles set status='active',must_change_password=true where id=uid;
 assert not ig_private.allowed('admin.read'),'Required password change bypassed';
 update public.ig_profiles set must_change_password=false where id=uid;
 delete from public.ig_consents where user_id=uid;
 assert not ig_private.allowed('admin.read'),'Missing consent bypassed';
 perform public.ig_account_update(jsonb_build_object('action','accept_policies','version',ig_private.current_policy(),'terms',true,'privacy',true,'dataUse',true,'adult',true));
 assert ig_private.allowed('admin.read'),'First recorded acceptance did not enable verified staff';
 update auth.sessions set not_after=now()-interval '1 minute' where id=sid;
 assert not ig_private.allowed('admin.read'),'Revoked session gained access';
 update auth.sessions set not_after=null where id=sid;
 update auth.users set email_confirmed_at=null where id=uid;
 assert not ig_private.allowed('admin.read'),'Unverified identity gained access';
 perform set_config('request.jwt.claims','{}',true);
 assert not ig_private.allowed('admin.read'),'Anonymous request gained staff access';
end $$;
rollback;
select '30 sign-in, recorded consent and permission assertions passed; all fixtures rolled back' as verification;
